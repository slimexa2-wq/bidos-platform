// Real React drawers; only the isolated, in-memory synthetic service is used.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const URL = 'http://127.0.0.1:7521';
let browser;
(async () => {
  const reset = await fetch('http://127.0.0.1:7522/__test__/control', { method: 'POST', body: JSON.stringify({ reset: true, mode: 'normal', delay: 0 }) });
  assert.equal((await reset.json()).fixture, 'bidos-ux-synthetic');
  browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
  const context = await browser.newContext();
  const page = await context.newPage();
  page.setDefaultTimeout(60000);
  page.setDefaultNavigationTimeout(60000);
  await page.goto(URL, { waitUntil: 'domcontentloaded' });
  assert.equal((await page.request.get(URL + '/api/workspace')).headers()['x-bidos-fixture'], 'ux-synthetic');
  await page.locator('.sidebar').getByRole('link', { name: '盲投信息', exact: true }).click();
  await page.getByRole('button', { name: '【演示】市民服务中心物业服务项目', exact: true }).click();
  await page.getByRole('button', { name: '编辑项目', exact: true }).click();
  await page.getByLabel('项目名称', { exact: true }).fill('【草稿】盲投路由保留');
  await page.goBack({ waitUntil: 'domcontentloaded' });
  await page.getByText('需要处理', { exact: true }).waitFor();
  await page.goForward({ waitUntil: 'domcontentloaded' });
  await page.getByRole('dialog').waitFor();
  assert.equal(await page.getByLabel('项目名称', { exact: true }).count(), 1, 'Back/Forward must restore the blind draft editor');
  assert.equal(await page.getByLabel('项目名称', { exact: true }).inputValue(), '【草稿】盲投路由保留');
  await page.reload({ waitUntil: 'domcontentloaded' });
  assert.equal(await page.getByLabel('项目名称', { exact: true }).inputValue(), '【草稿】盲投路由保留');
  const blindSave = page.waitForRequest(r => r.method() === 'POST' && r.url().endsWith('/portfolio/blind/p1/save'));
  await page.getByRole('button', { name: '保存到 Excel', exact: true }).click();
  assert.equal((await blindSave).postDataJSON().edits.find(x => x.field === '项目名称').value, '【草稿】盲投路由保留');
  await page.getByRole('button', { name: '编辑项目', exact: true }).waitFor();
  await page.getByRole('button', { name: '编辑项目', exact: true }).click();
  await page.getByLabel('项目名称', { exact: true }).fill('【丢弃】不应恢复');
  page.once('dialog', d => d.accept());
  await page.getByRole('button', { name: '取消', exact: true }).click();
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.getByRole('button', { name: '编辑项目', exact: true }).click();
  assert.equal(await page.getByLabel('项目名称', { exact: true }).inputValue(), '【草稿】盲投路由保留');
  await page.getByRole('button', { name: '取消', exact: true }).click();
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: '【演示】文化中心安保服务项目', exact: true }).click();
  await page.getByRole('button', { name: '编辑项目', exact: true }).click();
  assert.equal(await page.getByLabel('项目名称', { exact: true }).inputValue(), '【演示】文化中心安保服务项目');
  await page.getByRole('button', { name: '取消', exact: true }).click();
  await page.keyboard.press('Escape');
  console.log('PASS blind draft survives Back/Forward/reload; save and discard stay on the selected object');

  await page.getByRole('button', { name: '【草稿】盲投路由保留', exact: true }).click();
  await page.getByRole('button', { name: '编辑项目', exact: true }).click();
  await page.getByLabel('项目名称', { exact: true }).fill('【延迟保存】返回后显示最新项目');
  let release, arrived;
  const blocked = new Promise(resolve => { release = resolve; });
  const started = new Promise(resolve => { arrived = resolve; });
  await page.route('**/portfolio/blind/p1/save', async route => {
    arrived();
    await blocked;
    const response = await route.fetch();
    await route.fulfill({ response });
  });
  await page.getByRole('button', { name: '保存到 Excel', exact: true }).click();
  await started;
  await page.goBack({ waitUntil: 'domcontentloaded' });
  await page.getByText('需要处理', { exact: true }).waitFor();
  await page.goForward({ waitUntil: 'domcontentloaded' });
  await page.getByLabel('项目名称', { exact: true }).waitFor();
  const delayedResponse = page.waitForResponse(r => r.request().method() === 'POST' && r.url().endsWith('/portfolio/blind/p1/save'));
  release();
  assert.equal((await delayedResponse).status(), 200);
  await page.unroute('**/portfolio/blind/p1/save');
  await page.getByRole('button', { name: '编辑项目', exact: true }).waitFor();
  assert.equal(await page.locator('.blind-drawer-head h2').innerText(), '【延迟保存】返回后显示最新项目');
  await page.getByRole('button', { name: '编辑项目', exact: true }).click();
  assert.equal(await page.getByLabel('项目名称', { exact: true }).inputValue(), '【延迟保存】返回后显示最新项目');
  await page.getByRole('button', { name: '取消', exact: true }).click();
  await page.keyboard.press('Escape');
  console.log('PASS delayed blind save updates the remounted read-only drawer and its next edit');

  await page.getByRole('button', { name: '【延迟保存】返回后显示最新项目', exact: true }).click();
  await page.getByRole('button', { name: '编辑项目', exact: true }).click();
  await page.getByLabel('项目名称', { exact: true }).fill('【旧响应】第一个项目已保存');
  let releaseOlder, olderArrived;
  const olderBlocked = new Promise(resolve => { releaseOlder = resolve; });
  const olderStarted = new Promise(resolve => { olderArrived = resolve; });
  await page.route('**/portfolio/blind/p1/save', async route => {
    const response = await route.fetch();
    olderArrived();
    await olderBlocked;
    await route.fulfill({ response });
  });
  await page.getByRole('button', { name: '保存到 Excel', exact: true }).click();
  await olderStarted;
  await page.goBack({ waitUntil: 'domcontentloaded' });
  await page.getByText('需要处理', { exact: true }).waitFor();
  await page.goForward({ waitUntil: 'domcontentloaded' });
  await page.getByLabel('项目名称', { exact: true }).waitFor();
  page.once('dialog', d => d.accept());
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: '【演示】文化中心安保服务项目', exact: true }).click();
  await page.getByRole('button', { name: '编辑项目', exact: true }).click();
  await page.getByLabel('项目名称', { exact: true }).fill('【新保存】第二个项目保持最新');
  await page.getByRole('button', { name: '保存到 Excel', exact: true }).click();
  await page.getByRole('button', { name: '编辑项目', exact: true }).waitFor();
  assert.equal(await page.locator('.blind-drawer-head h2').innerText(), '【新保存】第二个项目保持最新');
  const savedNotice = page.getByText('已保存到桌面 Excel', { exact: true });
  await savedNotice.waitFor();
  await savedNotice.waitFor({ state: 'hidden' });
  const olderResponse = page.waitForResponse(r => r.request().method() === 'POST' && r.url().endsWith('/portfolio/blind/p1/save'));
  releaseOlder();
  assert.equal((await olderResponse).status(), 200);
  await savedNotice.waitFor();
  await page.unroute('**/portfolio/blind/p1/save');
  assert.equal(await page.locator('.blind-drawer-head h2').innerText(), '【新保存】第二个项目保持最新', 'An older whole-workspace save response must not undo a newer save on another project');
  await page.getByRole('button', { name: '编辑项目', exact: true }).click();
  assert.equal(await page.getByLabel('项目名称', { exact: true }).inputValue(), '【新保存】第二个项目保持最新');
  await page.getByRole('button', { name: '取消', exact: true }).click();
  await page.keyboard.press('Escape');
  console.log('PASS delayed blind response cannot regress a newer saved project after Back/Forward');

  await page.locator('.sidebar').getByRole('link', { name: '首页', exact: true }).click();
  await page.locator('.sidebar').getByRole('link', { name: '保证金台账', exact: true }).click();
  await page.getByRole('button', { name: '已退回', exact: true }).click();
  await page.getByLabel('备注（选填）').fill('【草稿】退回路由保留');
  await page.getByLabel('退回日期', { exact: true }).fill('2026-11-08');
  await page.goBack({ waitUntil: 'domcontentloaded' });
  await page.getByText('需要处理', { exact: true }).waitFor();
  await page.goForward({ waitUntil: 'domcontentloaded' });
  await page.getByRole('button', { name: '已退回', exact: true }).click();
  assert.equal(await page.getByLabel('备注（选填）').inputValue(), '【草稿】退回路由保留');
  assert.equal(await page.getByLabel('退回日期', { exact: true }).inputValue(), '2026-11-08');
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.getByRole('button', { name: '已退回', exact: true }).click();
  assert.equal(await page.getByLabel('备注（选填）').inputValue(), '【草稿】退回路由保留');
  page.once('dialog', d => d.dismiss());
  await page.keyboard.press('Escape');
  assert.equal(await page.getByLabel('备注（选填）').inputValue(), '【草稿】退回路由保留');
  page.once('dialog', d => d.accept());
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: '已退回', exact: true }).click();
  assert.equal(await page.getByLabel('备注（选填）').inputValue(), '');
  assert.notEqual(await page.getByLabel('退回日期', { exact: true }).inputValue(), '2026-11-08');
  console.log('PASS refund draft survives Back/Forward/reload/reopen; explicit discard clears its fields');
  await browser.close();
})().catch(async error => { console.error(error); if (browser) await browser.close(); process.exitCode = 1; });
